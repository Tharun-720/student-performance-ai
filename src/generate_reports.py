"""Generate result tables for the documentation directly from the saved JSON files.

Numbers are never typed by hand: docs/MODEL_EVALUATION_REPORT.md and
docs/EXPLAINABILITY_REPORT.md are written in full, and the block between
<!-- RESULTS:START --> and <!-- RESULTS:END --> in README.md and
docs/FINAL_TECHNICAL_REPORT.md is replaced with a headline table.
"""
import json
import re
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.paths import DOCS_DIR, MODELS_DIR, PROJECT_ROOT

START, END = "<!-- RESULTS:START -->", "<!-- RESULTS:END -->"


def _load(name):
    with open(MODELS_DIR / name, encoding="utf-8") as f:
        return json.load(f)


def headline_block(s, sens):
    reg, clf = s["regression_metrics"], s["classification_metrics"]
    br, bc = s["best_regressor"], s["best_classifier"]
    sp = s["evaluation_split"]
    rows = [
        "| Task | Selected model | Test result (held-out split) | No-learning reference |",
        "|---|---|---|---|",
        f"| Final score (0-100) | {br} | MAE **{reg[br]['MAE']:.2f}**, RMSE {reg[br]['RMSE']:.2f}, R² **{reg[br]['R2']:.3f}** | "
        f"\"final = G2\": MAE {reg['Naive (G3 = G2)']['MAE']:.2f}, R² {reg['Naive (G3 = G2)']['R2']:.3f} |",
        f"| Support tier | {bc} | accuracy **{clf[bc]['Accuracy']:.3f}**, macro-F1 **{clf[bc]['F1_Macro']:.3f}** | "
        f"tier from G2: accuracy {clf['Naive (tier from G2)']['Accuracy']:.3f}, macro-F1 {clf['Naive (tier from G2)']['F1_Macro']:.3f} |",
        "",
        f"Evaluation split: {sp['train_rows']} training and {sp['test_rows']} test records; a student's records never "
        f"appear on both sides. Models were selected by {sp['cv_folds']}-fold grouped cross-validation on the training "
        f"portion; the test split was used once. Without G1/G2 the same model family reaches only R² "
        f"{sens['without_G1_G2_trend']['R2']:.2f} (MAE {sens['without_G1_G2_trend']['MAE']:.1f}).",
    ]
    return "\n".join(rows)


def replace_block(path: Path, block: str):
    if not path.exists():
        return
    text = path.read_text(encoding="utf-8")
    if START not in text or END not in text:
        return
    new = re.sub(re.escape(START) + r".*?" + re.escape(END), START + "\n" + block + "\n" + END, text, flags=re.S)
    path.write_text(new, encoding="utf-8")


def evaluation_report(s, sens, meta):
    reg, clf = s["regression_metrics"], s["classification_metrics"]
    L = ["# Model Evaluation Report", "",
         "*Generated by `src/generate_reports.py` from `models/evaluation_summary.json`. Do not edit by hand.*", "",
         "## Evaluation design", "",
         f"- Records: {meta['train_samples'] + meta['test_samples']} (Maths + Portuguese stacked); "
         f"about {meta['distinct_student_fingerprints']} distinct students (estimated from matching attributes, "
         "because the dataset has no student id).",
         f"- Split: {s['evaluation_split']['split']['method']}. Training {s['evaluation_split']['train_rows']}, "
         f"test {s['evaluation_split']['test_rows']}; students present in both: "
         f"{s['evaluation_split']['split']['groups_in_both_splits']}.",
         "- Preprocessing (scaling, encoding, absence cap, defaults) is fitted on the training portion only.",
         f"- Model selection: {s['selection_criterion']['regression']}; classification: "
         f"{s['selection_criterion']['classification']}.",
         "- **Train R²** = fit on the training split; **Test R²** = held-out split; **CV** = out-of-fold on training.",
         "", "## Regression: final score (0-100)", "",
         "| Model | CV MAE | Test MAE | Test RMSE | Test R² | Train R² |", "|---|---|---|---|---|---|"]
    for k, v in reg.items():
        mark = " ★" if k == s["best_regressor"] else ""
        L.append(f"| {k}{mark} | {v['CV_MAE']:.2f} | {v['MAE']:.2f} | {v['RMSE']:.2f} | {v['R2']:.3f} | {v['Train_R2']:.3f} |")
    L += ["", f"Selected: **{s['best_regressor']}** (lowest CV MAE). Differences of a few tenths of a point between "
              "models are within the noise of a ~200-record test set. The \"Naive (G3 = G2)\" row needs no model.",
          "", "## Classification: support tier", "",
          "| Model | CV macro-F1 | Accuracy | Macro precision | Macro recall | Macro-F1 | ROC-AUC |", "|---|---|---|---|---|---|---|"]
    for k, v in clf.items():
        mark = " ★" if k == s["best_classifier"] else ""
        auc = "n/a" if v["ROC_AUC"] is None else f"{v['ROC_AUC']:.3f}"
        L.append(f"| {k}{mark} | {v['CV_F1_Macro']:.3f} | {v['Accuracy']:.3f} | {v['Precision_Macro']:.3f} | "
                 f"{v['Recall_Macro']:.3f} | {v['F1_Macro']:.3f} | {auc} |")
    bc = clf[s["best_classifier"]]
    L += ["", f"### Selected classifier: {s['best_classifier']}", "",
          "Confusion matrix (rows = actual, columns = predicted), classes in order " + ", ".join(s["classes"]) + ":", "",
          "```"]
    L += [str(row) for row in bc["Confusion_Matrix"]]
    L += ["```", "", "Recall per tier: " + ", ".join(f"{k} {v:.3f}" for k, v in bc["Recall_Per_Class"].items()) +
          ". Missing a student who needs High Support is the costly error, so per-tier recall matters more than accuracy.",
          "", "## Prediction range", "",
          f"Approximate 95% range = prediction + [{s['prediction_interval']['q025']:.1f}, {s['prediction_interval']['q975']:.1f}] "
          f"points (from {s['prediction_interval']['source']}).", "",
          "## Sensitivity analyses (`models/sensitivity_analysis.json`)", ""]
    rs = sens["random_vs_group_split"]
    r, g = rs["random_split_5_seeds"], rs["group_split_5_seeds"]
    L += ["| Scenario (default RF / XGBoost, 5 splits) | R² mean ± SD | MAE mean | macro-F1 mean |", "|---|---|---|---|",
          f"| Random split (same student can be in both sides) | {r['R2']['mean']:.3f} ± {r['R2']['sd']:.3f} | {r['MAE']['mean']:.2f} | {r['F1_Macro']['mean']:.3f} |",
          f"| Student-aware split | {g['R2']['mean']:.3f} ± {g['R2']['sd']:.3f} | {g['MAE']['mean']:.2f} | {g['F1_Macro']['mean']:.3f} |", "",
          f"Under a random split {sens['random_split_test_rows_with_same_student_in_train_pct']}% of test rows have the "
          "same student in the training set. Averaged over seeds this did **not** measurably change the scores, but "
          f"single splits vary (R² range {g['R2']['min']:.3f}-{g['R2']['max']:.3f} for the student-aware split), so one test number "
          "should not be over-interpreted.", "",
          "| Scenario (project split) | R² | MAE | macro-F1 |", "|---|---|---|---|"]
    z = sens["g3_zero_records"]
    for label, m in [("All features, all rows", sens["with_all_features_reference"]),
                     ("Rows with final grade 0 removed (train and test)", z["metrics_train_and_test_without_G3_zero"]),
                     ("Without G1, G2 and grade trend", sens["without_G1_G2_trend"])]:
        L.append(f"| {label} | {m['R2']:.3f} | {m['MAE']:.2f} | {m['F1_Macro']:.3f} |")
    L += ["", f"Records with final grade 0: {z['n_total']}; all {z['n_with_zero_absences']} have 0 recorded absences "
              f"({z['pct_zero_g3_among_zero_absence_students']}% of zero-absence students vs "
              f"{z['pct_zero_g3_among_students_with_absences']}% of students with absences). Correlation of absences with "
              f"G3: {z['corr_absences_G3_all']} with these rows, {z['corr_absences_G3_excluding_zero_G3']} without."]
    cl = s["clustering"]
    L += ["", "## Clustering (exploratory)", "",
          f"K-Means, k = {cl['k']}, features: {', '.join(cl['features'])}. Silhouette by k: "
          + ", ".join(f"k={k}: {v}" for k, v in cl["k_metrics"].items()) + ". " + cl["note"], ""]
    for cid, name in cl["archetype_names"].items():
        p = cl["profiles"][cid]
        L.append(f"- {name} ({p['size']} training records, {p['pct']}%; mean grade {p['mean_grade_G3']})")
    return "\n".join(L) + "\n"


def explainability_report(e):
    L = ["# Explainability Report", "",
         "*Generated by `src/generate_reports.py` from `models/explainability_summary.json`. Do not edit by hand.*", "",
         "Three different measures are reported; they answer different questions and need not agree:", "",
         "- **SHAP values**: additive contribution of each feature to one prediction (points of predicted score, 0-100).",
         "- **Permutation importance**: drop in test R² when a feature is shuffled (can exceed 1 when shuffling makes predictions worse than the mean).",
         "- **Tree importance**: how much the fitted trees used a feature while training.", "",
         f"Model explained: **{e['model']}**; rows: {e['n_rows_explained']} (the whole test split). "
         f"SHAP method: `shap.TreeExplainer`. Base value (average prediction): **{e.get('base_value')}**. "
         f"Additivity check (base + sum of SHAP vs model output): max gap {e.get('additivity_max_gap_points')} points.", "",
         "## Global ranking", "", "| Rank | Feature | Mean abs SHAP | Permutation importance | Tree importance |", "|---|---|---|---|---|"]
    perm, tree = e["global_permutation_importance"], e.get("global_tree_importance", {})
    for i, d in enumerate(e["global_shap_importance"][:10], 1):
        f = d["feature"]
        L.append(f"| {i} | {f} | {d['mean_abs_shap']:.3f} | {perm.get(f, '<top-15 cut-off')} | {tree.get(f, '<top-15 cut-off')} |")
    L += ["", "G2 (second-period grade) dominates every method. SHAP describes what the **model** relies on; "
              "it does not show what causes a student's result.", "", "## Case studies", "",
          "Real records from the test split, chosen by a fixed rule (not hand-picked).", ""]
    for cs in e["case_studies"]:
        L += [f"### {cs['title']}", "",
              f"{cs['subject']} · G1 {cs['G1']:g}, G2 {cs['G2']:g}, absences {cs['absences']:g}, failures {cs['failures']}, "
              f"study time {cs['studytime']} · actual **{cs['actual_score_pct']}%** · predicted **{cs['predicted_score_pct']}%**.", "",
              "- Raise the prediction: " + ", ".join(f"{d['feature']} ({d['shap']:+.1f})" for d in cs["increasing_features"]),
              "- Lower the prediction: " + ", ".join(f"{d['feature']} ({d['shap']:+.1f})" for d in cs["decreasing_features"])]
        if cs["note"]:
            L += ["", f"*{cs['note']}*"]
        L.append("")
    return "\n".join(L)


def main():
    s, e, sens, meta = _load("evaluation_summary.json"), _load("explainability_summary.json"), \
        _load("sensitivity_analysis.json"), _load("feature_metadata.json")
    (DOCS_DIR / "MODEL_EVALUATION_REPORT.md").write_text(evaluation_report(s, sens, meta), encoding="utf-8")
    (DOCS_DIR / "EXPLAINABILITY_REPORT.md").write_text(explainability_report(e), encoding="utf-8")
    block = headline_block(s, sens)
    replace_block(PROJECT_ROOT / "README.md", block)
    replace_block(DOCS_DIR / "FINAL_TECHNICAL_REPORT.md", block)
    print("Reports generated in", DOCS_DIR)


if __name__ == "__main__":
    main()
